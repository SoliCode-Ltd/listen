$total = 0;
foreach ($cases as $slug => $case) {
    $text = $case['text'];
    unset($case['text']);
    $total += mb_strlen($text);
    try {
        $made = app(GeminiTtsProvider::class)->synthesize($text, 'ar', $case + ['performance_style' => 'neutral', 'emotion' => 'neutral']);
        $file = Storage::disk('public')->path($made['audio_path']);
        copy($file, $out.'/'.$slug.'.'.pathinfo($file, PATHINFO_EXTENSION));
        echo "made {$slug} (".mb_strlen($text)." characters)\n";
